"""FAQ mining, review state machine, permission checks and the FAQ answer cache.

Mining (background job ``faq_mine``) — only ever produces CANDIDATES:

1. Source: real chat messages of the knowledge base (window ``days``) that were answered (ok / partial_answer) by the
   RAG pipeline with validated citations, not hidden, not themselves FAQ answers; non-compliant questions are dropped
   (personal data, identifiers, credentials, length).
2. Embeddings of the questions (platform model, bge-m3) → greedy centroid clustering with ``cluster_threshold``.
3. Inside each semantic cluster, members are split by their EVIDENCE DOCUMENT SET (documents cited by their answers).
   A candidate therefore only ever combines questions whose answers were grounded in the same documents, and its
   audience is exactly the users who can read all those documents (global / department / role / user FAQs emerge
   from the documents' ACL — no separate FAQ ACL that could drift).
4. Groups with frequency ≥ ``min_frequency`` become candidates (or update the matching existing entry).
5. The candidate answer is generated by the unchanged phase-1 pipeline under a synthetic principal that can read
   ONLY the evidence documents (so the answer cannot draw on anything else); fallback: the most recent member answer.
6. Recorded: frequency, distinct users, mean similarity, confidence, embedding model, LLM model + digest, index
   generation, evidence document versions, thresholds.

Review: candidate → published | rejected; published → retired; retired → published. A reviewer must be able to
MANAGE the knowledge base AND READ every evidence document; otherwise the entry is invisible to them (not even the
member questions are shown). Member user ids are never returned.

Serving (``match``): a published FAQ answers a question only if the question embedding is similar enough, the user
can read every evidence document NOW, every evidence document is still active at the recorded version, and every
cited chunk is present in the ACTIVE index generation. Anything else → normal RAG. All checks run on every request
(no FAQ-level cache), so retire / ACL change / disable / delete / new version / re-index take effect immediately.
"""

from __future__ import annotations

import hashlib
import re
from datetime import timezone
from collections import Counter, defaultdict
from typing import Any, Dict, List, Optional, Tuple

from sqlalchemy import select
from sqlalchemy.orm import Session

from ragas_eval.acl import AclPolicy

from ..acl_store import can_manage, document_entry, kb_by_id
from ..models import ChatMessage, ChatSession, Document, DocumentVersion, KnowledgeBase, User, utcnow
from ..models_ops import FaqEntry, FaqEvent, FaqMember
from .common import compliance_problem, embed, readable_doc_ids

TRANSITIONS = {("candidate", "publish"): "published", ("candidate", "reject"): "rejected",
               ("published", "retire"): "retired", ("retired", "publish"): "published"}
GENERATOR = "__faq_generator__"
HEX12 = re.compile(r"(?<![0-9a-fA-F])[0-9a-f]{12}(?![0-9a-fA-F])")


class FaqError(Exception):
    def __init__(self, status: int, code: str, message: str):
        super().__init__(code)
        self.status, self.code, self.message = status, code, message


def _key(doc_ids) -> str:
    return hashlib.sha256(",".join(sorted(doc_ids)).encode()).hexdigest()[:32]


def evidence_doc_ids(faq: FaqEntry) -> List[str]:
    return sorted({e["document_id"] for e in faq.evidence or []})


def evidence_state(db: Session, faq: FaqEntry) -> Tuple[bool, str]:
    """(valid, reason). Valid = every evidence document active and still at the recorded version."""
    if not faq.evidence:
        return False, "no_evidence"
    for e in faq.evidence:
        d = db.get(Document, e["document_id"])
        if d is None or d.status == "deleted":
            return False, "document_deleted"
        if d.status != "active":
            return False, "document_disabled"
        if d.current_version_id != e["version_id"]:
            return False, "document_updated"
    return True, "ok"


def can_read(db: Session, user: User, faq: FaqEntry, kb: Optional[KnowledgeBase] = None) -> bool:
    kb = kb or kb_by_id(db, faq.kb_id)
    need = set(evidence_doc_ids(faq))
    return bool(need) and kb is not None and need <= readable_doc_ids(db, user, kb)


def can_review(db: Session, user: User, faq: FaqEntry) -> bool:
    kb = kb_by_id(db, faq.kb_id)
    return kb is not None and can_manage(db, user, kb) and can_read(db, user, faq, kb)


def log(db: Session, faq: FaqEntry, actor: str, action: str, frm: Optional[str], to: Optional[str], note: str = ""):
    db.add(FaqEvent(faq_id=faq.id, actor=actor[:64], action=action, from_status=frm, to_status=to, note=(note or None)))


def transition(db: Session, faq: FaqEntry, action: str, actor: str, note: str = "") -> FaqEntry:
    to = TRANSITIONS.get((faq.status, action))
    if to is None:
        raise FaqError(409, "invalid_transition", f"状态为 {faq.status} 的 FAQ 不能执行 {action}")
    if action == "publish":
        ok, reason = evidence_state(db, faq)
        if not ok:
            raise FaqError(409, "evidence_invalid", f"证据文档已变化（{reason}），请重新挖掘或驳回")
        if not faq.answer.strip():
            raise FaqError(422, "empty_answer", "标准答案不能为空")
        faq.published_at = utcnow()
    frm = faq.status
    faq.status, faq.reviewed_by, faq.reviewed_at = to, actor[:64], utcnow()
    faq.review_note = (note or None)
    log(db, faq, actor, action, frm, to, note)
    return faq


def edit(db: Session, faq: FaqEntry, actor: str, question: Optional[str], answer: Optional[str]) -> FaqEntry:
    if faq.status not in ("candidate", "retired"):
        raise FaqError(409, "not_editable", "只有候选或已下线的 FAQ 可以编辑（已发布的请先下线）")
    if answer is not None:
        allowed = {c["chunk_id"] for c in faq.citations or []}
        # an edited answer may only reference the recorded evidence chunks
        answer = HEX12.sub(lambda m: m.group(0) if m.group(0) in allowed else "", answer)
        faq.answer, faq.answer_source = answer.strip(), "edited"
    if question is not None:
        faq.question = question.strip()
    faq.revision += 1
    log(db, faq, actor, "edit", faq.status, faq.status)
    return faq


