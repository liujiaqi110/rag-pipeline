def _generate_answer(db: Session, backend: Any, kb: KnowledgeBase, question: str, doc_ids: List[str], retriever: Any,
                     generation: str) -> Tuple[Optional[dict], str]:
    """Phase-1 pipeline under a synthetic principal limited to the evidence documents."""
    docs = [db.get(Document, i) for i in doc_ids]
    data = {"policy_version": f"faq-{kb.id}",
            "users": {GENERATOR: {"roles": [], "departments": [], "clearance": 3, "active": True}},
            "documents": {}}
    for d in docs:
        e = document_entry(d)
        e["allow"], e["deny"] = {"users": [GENERATOR]}, {}
        data["documents"][d.doc_key] = e
    try:
        user_resp, summary, _ = backend.ask(AclPolicy(data), GENERATOR, kb.id, question, retriever=retriever,
                                            generation=f"faqgen-{generation}")
    except Exception:  # noqa: BLE001
        return None, "generation_failed"
    if user_resp.get("status") in ("ok", "partial_answer") and user_resp.get("citations"):
        return dict(user_resp, _model=summary.get("model")), "generated"
    return None, user_resp.get("status") or "no_answer"


def mine(db: Session, backend: Any, settings: Any, kb_id: str, actor: str, params: Dict[str, Any]) -> Dict[str, Any]:
    import numpy as np
    kb = kb_by_id(db, kb_id)
    if kb is None:
        return {"failed": True, "error_code": "kb_not_found", "error_message": "知识库不存在"}
    threshold = float(params.get("similarity_threshold") or settings.faq_cluster_threshold)
    min_freq = int(params.get("min_frequency") or settings.faq_min_frequency)
    days = int(params.get("days") or 30)
    since = utcnow().timestamp() - days * 86400
    from ..models_ops import QaEvent
    faq_msgs = {e.message_id for e in db.scalars(select(QaEvent).where(QaEvent.kb_id == kb_id, QaEvent.source == "faq"))}
    rows = db.execute(select(ChatMessage, ChatSession.user_id).join(ChatSession, ChatSession.id == ChatMessage.session_id)
                      .where(ChatSession.kb_id == kb_id, ChatMessage.status.in_(("ok", "partial_answer")))
                      .order_by(ChatMessage.id)).all()
    stats = Counter()
    items = []
    for m, uid in rows:
        if m.id in faq_msgs or m.scope_key == "revoked" or not m.citations:
            stats["skipped_not_rag_answer"] += 1
            continue
        ts = m.created_at if m.created_at.tzinfo else m.created_at.replace(tzinfo=timezone.utc)
        if ts.timestamp() < since:
            stats["skipped_outside_window"] += 1
            continue
        if compliance_problem(m.question):
            stats["skipped_non_compliant"] += 1
            continue
        docs = {c.get("source") for c in m.citations}
        dmap = {d.doc_key: d for d in db.scalars(select(Document).where(Document.doc_key.in_(docs)))}
        if len(dmap) != len(docs):
            stats["skipped_unknown_document"] += 1
            continue
        items.append({"m": m, "uid": uid, "docs": sorted(d.id for d in dmap.values())})
    stats["eligible"] = len(items)
    if not items:
        return {"candidates_created": 0, "candidates_updated": 0, "clusters": 0, "stats": dict(stats)}
    vecs = embed(backend, [x["m"].question for x in items])
    # greedy centroid clustering (deterministic: chronological order)
    clusters: List[Dict[str, Any]] = []
    for i, v in enumerate(vecs):
        best, sim = None, -1.0
        for c in clusters:
            s = float(np.dot(c["centroid"], v))
            if s > sim:
                best, sim = c, s
        if best is not None and sim >= threshold:
            best["idx"].append(i)
            cen = vecs[best["idx"]].mean(axis=0)
            best["centroid"] = cen / (np.linalg.norm(cen) or 1.0)
        else:
            clusters.append({"idx": [i], "centroid": v})
    active = backend.index.active_generation(db) if not backend.external else None
    retriever = backend.index.retriever(active) if active is not None else None
    generation = active.id if active is not None else "external"
    try:
        info = backend.llm().model_info()
    except Exception:  # noqa: BLE001
        info = {}
    emb_model = getattr(backend.index.embedder(), "name", None) or settings.embedding_model
    created = updated = 0
    for c in clusters:
        groups = defaultdict(list)
        for i in c["idx"]:
            groups[tuple(items[i]["docs"])].append(i)
        for doc_ids, idx in groups.items():
            if len(idx) < min_freq:
                stats["groups_below_threshold"] += 1
                continue
            sims = [float(np.dot(c["centroid"], vecs[i])) for i in idx]
            rep_i = idx[int(np.argmax(sims))]
            rep = items[rep_i]["m"]
            ekey = _key(doc_ids)
            existing = None
            for f in db.scalars(select(FaqEntry).where(FaqEntry.kb_id == kb_id, FaqEntry.evidence_key == ekey,
                                                       FaqEntry.status.in_(("candidate", "published", "retired")))):
                if f.embeddings and max(float(np.dot(np.asarray(e), c["centroid"])) for e in f.embeddings) >= threshold:
                    existing = f
                    break
            known = set()
            if existing is not None:
                known = {mm.message_id for mm in db.scalars(select(FaqMember).where(FaqMember.faq_id == existing.id))}
            new_idx = [i for i in idx if items[i]["m"].id not in known]
            evidence = []
            for did in doc_ids:
                d = db.get(Document, did)
                v = db.get(DocumentVersion, d.current_version_id) if d.current_version_id else None
                evidence.append({"document_id": d.id, "version_id": d.current_version_id,
                                 "version_no": v.version_no if v else None, "title": d.title or d.doc_key,
                                 "source": d.doc_key})
            if existing is None:
                resp, how = _generate_answer(db, backend, kb, rep.question, list(doc_ids), retriever, generation)
                if resp is None:   # fallback: most recent member answer (already validated by the safety layer)
                    last = items[idx[-1]]["m"]
                    resp, how = {"answer": last.answer, "citations": last.citations}, "member_answer"
                cites = [dict(cc) for cc in resp.get("citations") or []]
                docs_now = {d.doc_key: d for d in db.scalars(select(Document).where(Document.id.in_(doc_ids)))}
                cites = [dict(cc, document_id=docs_now[cc["source"]].id, version_id=docs_now[cc["source"]].current_version_id)
                         for cc in cites if cc.get("source") in docs_now]
                f = FaqEntry(kb_id=kb_id, status="candidate", question=rep.question.strip(), answer=resp.get("answer", ""),
                             citations=cites, evidence=evidence, evidence_key=ekey, embeddings=[],
                             answer_source=how, embedding_model=emb_model,
                             llm_model=str(resp.get("_model") or info.get("model") or ""),
                             llm_digest=str(info.get("digest") or ""), index_generation=generation,
                             params={"similarity_threshold": threshold, "min_frequency": min_freq, "days": days})
                db.add(f)
                db.flush()
                log(db, f, actor, "mined", None, "candidate", f"frequency={len(idx)}")
                created += 1
            else:
                f = existing
                if f.status == "candidate":
                    f.evidence = evidence
                if not new_idx:              # nothing new for this entry: no history noise, not counted as updated
                    continue
                log(db, f, actor, "remined", f.status, f.status, f"new_members={len(new_idx)}")
                updated += 1
            for i in new_idx:
                m = items[i]["m"]
                db.add(FaqMember(faq_id=f.id, message_id=m.id, user_id=items[i]["uid"], question=m.question,
                                 similarity=float(np.dot(c["centroid"], vecs[i])), asked_at=m.created_at))
            db.flush()
            members = list(db.scalars(select(FaqMember).where(FaqMember.faq_id == f.id)))
            f.frequency = len(members)
            f.distinct_users = len({mm.user_id for mm in members})
            f.similarity_mean = round(sum(mm.similarity for mm in members) / len(members), 4)
            f.embeddings = [c["centroid"].round(5).tolist()] + [vecs[i].round(5).tolist() for i in idx][:20]
            # confidence: cohesion of the cluster, how many people asked, whether the answer was freshly generated
            f.confidence = round(min(1.0, 0.6 * f.similarity_mean + 0.25 * min(1.0, f.frequency / (2 * min_freq))
                                     + 0.15 * (1.0 if f.answer_source == "generated" else 0.5)), 4)
    stats["clusters"] = len(clusters)
    return {"candidates_created": created, "candidates_updated": updated, "clusters": len(clusters), "stats": dict(stats)}


