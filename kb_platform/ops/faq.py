def match(db: Session, backend: Any, settings: Any, user: User, kb: KnowledgeBase, question: str,
          retriever: Any) -> Optional[Dict[str, Any]]:
    """Return a FAQ hit (answer, citations, faq) or None → normal RAG."""
    if not settings.faq_enabled or backend.external or retriever is None:
        return None
    faqs = list(db.scalars(select(FaqEntry).where(FaqEntry.kb_id == kb.id, FaqEntry.status == "published")))
    if not faqs:
        return None
    import numpy as np
    try:
        q = embed(backend, [question])[0]
    except Exception:  # noqa: BLE001 — no embedding model: no FAQ serving (never a fuzzy fallback)
        return None
    scored = []
    for f in faqs:
        if f.embeddings:
            scored.append((max(float(np.dot(np.asarray(e, dtype="float32"), q)) for e in f.embeddings), f))
    scored.sort(key=lambda x: -x[0])
    readable = readable_doc_ids(db, user, kb)
    live_chunks = {d["chunk_id"] for d in retriever.bm25.documents}
    for sim, f in scored:
        if sim < settings.faq_match_threshold:
            break
        if not set(evidence_doc_ids(f)) <= readable:          # permission boundary
            continue
        if not evidence_state(db, f)[0]:                     # disabled / deleted / updated evidence
            continue
        if not f.citations or any(c["chunk_id"] not in live_chunks for c in f.citations):   # index generation
            continue
        f.hit_count = (f.hit_count or 0) + 1
        return {"faq": f, "similarity": round(sim, 4),
                "answer": f.answer, "citations": [{"chunk_id": c["chunk_id"], "source": c["source"],
                                                    "version_id": c.get("version_id")} for c in f.citations]}
    return None
