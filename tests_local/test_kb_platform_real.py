"""REAL integration for the P3 ingestion pipeline — NOT run in CI, NO mocks for retrieval or generation:

* Dense = the real local BAAI/bge-m3 (sentence-transformers, offline, never downloaded by this test);
* BM25 = scripts/06 index + scripts/10 search (as everywhere);
* LLM  = the real local Ollama qwen2.5:7b (skipped if not running).

    $env:HF_HOME="<local HuggingFace cache dir>"; $env:HF_HUB_OFFLINE="1"; $env:TRANSFORMERS_OFFLINE="1"
    .venv\\Scripts\\python -m unittest tests_local.test_kb_platform_real -v

Uses only synthetic documents generated by kb_platform/tests/ingest_fixtures.py.
"""

import json
import os
import shutil
import tempfile
import unittest
from pathlib import Path


def _bge_available() -> bool:
    try:
        from ragas_eval.dataset_adapter import get_sentence_transformer
        get_sentence_transformer("BAAI/bge-m3", "cpu")
        return True
    except Exception:  # noqa: BLE001
        return False


def _ollama_available() -> bool:
    try:
        from ragas_eval.local_llm import OllamaClient
        return OllamaClient().model_info().get("model") == "qwen2.5:7b"
    except Exception:  # noqa: BLE001
        return False


HAVE_BGE = _bge_available()
HAVE_OLLAMA = HAVE_BGE and _ollama_available()


class RecordingOllama:
    def __init__(self):
        from ragas_eval.local_llm import OllamaClient
        self.inner, self.prompts = OllamaClient(), []

    def chat(self, messages, options, fmt=None):
        self.prompts.append("\n".join(m["content"] for m in messages))
        return self.inner.chat(messages, options)


@unittest.skipUnless(HAVE_BGE, "local BAAI/bge-m3 + sentence-transformers not available")
class TestRealDenseIngestion(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        from fastapi.testclient import TestClient
        from kb_platform import security
        from kb_platform.app import create_app
        from kb_platform.cli import seed_example
        from kb_platform.ingest.manager import IndexManager
        from kb_platform.models import User
        from kb_platform.rag_backend import AnswerCache, RagBackend
        from kb_platform.settings import Settings
        cls.tmp = Path(tempfile.mkdtemp(prefix="kb_real_"))
        # inline jobs: the P3 synchronous contract on the same job code path (the async 202 path with the real
        # models is covered by the browser end-to-end suite, frontend/e2e)
        st = Settings(database_url="sqlite://", storage_dir=str(cls.tmp / "storage"), dense_mode="required",
                      retrieval_mode="rrf", jobs_mode="inline")
        cls.index = IndexManager(st)                       # default embedder: the real bge-m3
        cls.llm = RecordingOllama() if HAVE_OLLAMA else None
        backend = RagBackend(index=cls.index, llm_factory=(lambda: cls.llm) if cls.llm else None,
                             mode="rrf", cache=AnswerCache(0, 0))
        cls.app = create_app(st, backend)
        cls.c = TestClient(cls.app)
        out = seed_example(cls.app.state.sessionmaker, cls.tmp / "creds.json")
        cls.kb = out["kb_id"]
        cls.creds = json.loads((cls.tmp / "creds.json").read_text(encoding="utf-8"))
        with cls.app.state.sessionmaker() as db:
            db.add(User(username="real_admin", password_hash=security.hash_password("Real-admin-001"), is_admin=True))
            db.commit()
        cls.creds["real_admin"] = "Real-admin-001"

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def h(self, u):
        t = self.c.post("/api/v1/auth/login", json={"username": u, "password": self.creds[u]}).json()["access_token"]
        return {"Authorization": f"Bearer {t}"}

    def upload(self, name, data):
        r = self.c.post(f"/api/v1/knowledge-bases/{self.kb}/documents/upload", files={"file": (name, data)},
                        headers=self.h("real_admin"))
        self.assertEqual(r.status_code, 201, r.text)
        return r.json()

    def grant(self, did, **allow):
        self.assertEqual(self.c.put(f"/api/v1/documents/{did}/acl", headers=self.h("real_admin"),
                                    json={"allow": allow}).status_code, 200)

    def test_real_pipeline(self):
        from kb_platform.tests.ingest_fixtures import docx_doc, md_doc, pdf_report, txt_doc
        docs = {}
        for name, data in (("eng_release.md", md_doc("发布手册", "REAL-CANARY-ENG", "发布流程")),
                           ("hr_doors.txt", txt_doc("REAL-CANARY-HR")),
                           ("eng_report.pdf", pdf_report("REAL-CANARY-PDF")),
                           ("fin_purchase.docx", docx_doc("REAL-CANARY-FIN"))):
            b = self.upload(name, data)
            self.assertEqual((b["version"]["status"], b["index"]["dense"]), ("indexed", True), name)
            docs[name] = b["document"]["id"]
        self.grant(docs["eng_release.md"], departments=["engineering"])
        self.grant(docs["eng_report.pdf"], departments=["engineering"])
        self.grant(docs["hr_doors.txt"], departments=["hr"])
        self.grant(docs["fin_purchase.docx"], departments=["finance"])
        with self.app.state.sessionmaker() as db:
            gen = self.index.active_generation(db)
            self.assertTrue(gen.dense)
            self.assertEqual(gen.dense_model, "BAAI/bge-m3")
            r = self.index.retriever(gen)
        self.assertEqual(r.E.shape[1], 1024)                     # real bge-m3 vectors
        from ragas_eval import acl as A
        from ragas_eval.acl_retrieval import AclRetriever
        from kb_platform.acl_store import policy_for
        from kb_platform.models import KnowledgeBase, User
        from sqlalchemy import select
        with self.app.state.sessionmaker() as db:
            alice = db.scalar(select(User).where(User.username == "eng_alice"))
            pol = policy_for(db, alice, db.get(KnowledgeBase, self.kb))
        scope = A.build_scope(pol, "eng_alice", {d["chunk_id"]: d["source_file"] for d in r.bm25.documents},
                              dict(zip(r.ids, r.src)))
        ar = AclRetriever(r, scope)
        # semantic (paraphrased, little lexical overlap) query → real Dense finds the release runbook
        de = ar.dense("上线之前需要准备哪些保障措施？")
        self.assertTrue(de)
        self.assertTrue(de[0]["chunk"]["source_file"].endswith("eng_release.md"), de[0])
        for lst in (de, ar.bm25_full("采购 供应商 门禁"), ar.rrf("采购 供应商 门禁 预算")):
            self.assertTrue(all(scope.allows_chunk(x["chunk"]["chunk_id"]) for x in lst))
            self.assertFalse(any(x["chunk"]["source_file"].endswith(("hr_doors.txt", "fin_purchase.docx")) for x in lst))
        en = ar.dense("what must happen before booking a release window")
        self.assertTrue(en[0]["chunk"]["source_file"].endswith(("eng_report.pdf", "eng_release.md")))
        # version update with real embeddings
        did = docs["eng_release.md"]
        b = self.c.post(f"/api/v1/documents/{did}/versions", headers=self.h("real_admin"),
                        files={"file": ("eng_release.md", md_doc("发布手册", "REAL-CANARY-ENG-V2", "发布流程"))}).json()
        self.assertEqual((b["version"]["version_no"], b["version"]["status"], b["index"]["dense"]), (2, "indexed", True))
        with self.app.state.sessionmaker() as db:
            r2 = self.index.retriever(self.index.active_generation(db))
        texts = " ".join(d["text"] for d in r2.bm25.documents)
        self.assertIn("REAL-CANARY-ENG-V2", texts)
        self.assertNotIn("REAL-CANARY-ENG。", texts)

    @unittest.skipUnless(HAVE_OLLAMA, "local Ollama qwen2.5:7b not running")
    def test_real_llm_answer_respects_acl(self):
        from kb_platform.tests.ingest_fixtures import md_doc
        did = self.upload("eng_rollback.md", md_doc("回滚规范", "REAL-CANARY-RB", "回滚演练"))["document"]["id"]
        sec = self.upload("hr_salary.md", md_doc("薪酬规范", "REAL-CANARY-SAL", "回滚演练薪酬"))["document"]["id"]
        self.grant(did, departments=["engineering"])
        self.grant(sec, departments=["hr"])
        h = self.h("eng_alice")
        sid = self.c.post("/api/v1/sessions", json={"kb_id": self.kb}, headers=h).json()["id"]
        n0 = len(self.llm.prompts)
        r = self.c.post(f"/api/v1/sessions/{sid}/ask", json={"question": "回滚演练有哪些要求？"}, headers=h)
        self.assertEqual(r.status_code, 200, r.text)
        body = r.json()
        prompts = "\n".join(self.llm.prompts[n0:])
        self.assertIn("REAL-CANARY-RB", prompts)
        self.assertNotIn("REAL-CANARY-SAL", prompts + r.text)
        self.assertIn(body["status"], ("ok", "partial_answer", "refused"))
        self.assertTrue(all(not c["source"].endswith("hr_salary.md") for c in body["citations"]))
        print("\n[real qwen2.5:7b] status:", body["status"], "| citations:", [c["source"] for c in body["citations"]])


if __name__ == "__main__":
    unittest.main()
